from tortoise import BaseDBAsyncClient

RUN_IN_TRANSACTION = True


async def upgrade(db: BaseDBAsyncClient) -> str:
    # A stock request line may ask for an Item this branch doesn't carry yet (from head office's list): its Item link
    # becomes optional and the line keeps the Item's name and unit itself. SQLite can't loosen a column in place, so
    # the table is rebuilt with the same rows.
    return """
        CREATE TABLE "stock_request_lines_new" (
    "id" CHAR(36) NOT NULL PRIMARY KEY,
    "sku" VARCHAR(60) NOT NULL,
    "name" VARCHAR(200),
    "unit" VARCHAR(30),
    "qty_requested" VARCHAR(40) NOT NULL,
    "qty_approved" VARCHAR(40),
    "on_hand" VARCHAR(40),
    "daily_sales" VARCHAR(40),
    "product_id" VARCHAR(40) REFERENCES "products" ("id") ON DELETE CASCADE,
    "request_id" CHAR(36) NOT NULL REFERENCES "stock_requests" ("id") ON DELETE CASCADE
);
        INSERT INTO "stock_request_lines_new" ("id", "sku", "name", "unit", "qty_requested", "qty_approved", "on_hand", "daily_sales", "product_id", "request_id")
    SELECT l."id", l."sku", p."name", p."unit", l."qty_requested", l."qty_approved", l."on_hand", l."daily_sales", l."product_id", l."request_id"
    FROM "stock_request_lines" l LEFT JOIN "products" p ON p."id" = l."product_id";
        DROP TABLE "stock_request_lines";
        ALTER TABLE "stock_request_lines_new" RENAME TO "stock_request_lines";"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    # Back to every line needing an Item this branch has: lines for Items it never took are dropped.
    return """
        CREATE TABLE "stock_request_lines_old" (
    "id" CHAR(36) NOT NULL PRIMARY KEY,
    "sku" VARCHAR(60) NOT NULL,
    "qty_requested" VARCHAR(40) NOT NULL,
    "qty_approved" VARCHAR(40),
    "on_hand" VARCHAR(40),
    "daily_sales" VARCHAR(40),
    "product_id" VARCHAR(40) NOT NULL REFERENCES "products" ("id") ON DELETE CASCADE,
    "request_id" CHAR(36) NOT NULL REFERENCES "stock_requests" ("id") ON DELETE CASCADE
);
        INSERT INTO "stock_request_lines_old" ("id", "sku", "qty_requested", "qty_approved", "on_hand", "daily_sales", "product_id", "request_id")
    SELECT "id", "sku", "qty_requested", "qty_approved", "on_hand", "daily_sales", "product_id", "request_id"
    FROM "stock_request_lines" WHERE "product_id" IS NOT NULL;
        DROP TABLE "stock_request_lines";
        ALTER TABLE "stock_request_lines_old" RENAME TO "stock_request_lines";"""



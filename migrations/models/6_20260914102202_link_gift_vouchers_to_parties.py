# Hand-corrected. Aerich emitted `ALTER TABLE ... ADD CONSTRAINT ... FOREIGN KEY`, which is
# Postgres/MySQL syntax — SQLite has no ADD CONSTRAINT and the migration would abort. SQLite does
# accept the reference inline on ADD COLUMN, provided the new column defaults to NULL, which a
# nullable FK does. Existing vouchers get party_id NULL: they stay open vouchers, exactly as they
# behaved before.
async def upgrade(db: BaseDBAsyncClient) -> str:
    return """
        ALTER TABLE "gift_vouchers" ADD "party_id" CHAR(36) REFERENCES "parties" ("id") ON DELETE RESTRICT;"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        ALTER TABLE "gift_vouchers" DROP COLUMN "party_id";"""


